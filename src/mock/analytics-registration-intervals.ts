import type { RegistrationIntervalDay } from "@/types";

function bucket(isoDate: string, hour: number, minute: number, count: number) {
  return {
    bucketStart: `${isoDate}T${String(hour).padStart(2, "0")}:${String(minute).padStart(2, "0")}:00+05:30`,
    count,
  };
}

